class NumpyEncoder(json.JSONEncoder):
    """
    Dict marshaler for JSON serialization.
    Solution may contains numpy arrays. Use this encoder for serializing the solution dict before json.dump().
    """
    def default(self, obj):
        if isinstance(obj, np.integer):
            return int(obj)
        elif isinstance(obj, np.floating):
            return float(obj)
        elif isinstance(obj, np.ndarray):
            return obj.tolist()
        return super().default(obj)
    
    
# Internal functions used for sampling
def _softmax(logits: Union[np.ndarray, list], temperature: float) -> np.ndarray:
    """
    Returns the tempered softmax of 1D finite `logits`.
    Used to sample from clusters within an island, and to sample programs within a cluster.
    Cf. FunSearch, p9
    When sampling a cluster, we favour those with larger score values.
    When sampling a program within a cluster, we favour shorter programs.
    
    Args:
        logits: 1D array of logits.
        temperature: Temperature parameter.
    
    Returns:
        1D array of probabilities.
    """
    if isinstance(logits, List):
        logits = np.asarray(logits, dtype=np.float32)
        
    if not np.all(np.isfinite(logits)):
        non_finites = set(logits[~np.isfinite(logits)])
        raise ValueError(f'`logits` contains non-finite value(s): {non_finites}')
    
    if not np.issubdtype(logits.dtype, np.floating):
        logits = np.array(logits, dtype=np.float32)

    result = scipy.special.softmax(logits / temperature, axis=-1)

    # Ensure that probabilities sum to 1 to prevent error in `np.random.choice`.
    index = np.argmax(result)
    result[index] = 1 - np.sum(result[0:index]) - np.sum(result[index+1:])
    return result




class SolutionDatabase:
    """
    A collection of solutions, organized as islands.
    """
    def __init__(self, checkpoint=None, config=None) -> None:
        # =====General configuration start (common for all agents)=====
        self.package_dir = Path(__file__).parent
        self.project_root = Path.cwd()
        # Problem data is stored in `<project_root>/problems`
        # Prompts are stored in `<project_root>/prompts`
        
        if checkpoint:  # if checkpoint specified, load checkpoint
            self.load(checkpoint=checkpoint)
        elif config:  # else, check if config is provided
            self.config = config
        else:  # else, use default config
            # Load built-in config if config is not provided
            with open(f'{self.package_dir}/config.yaml', 'r') as f:
                self.config = yaml.safe_load(f)
                
        self.algorithm = self.config['algorithm'].lower().strip()
        self.problem = self.config['problem'].lower().strip()  # the problem to solve
        # Load experiment config if not provided
        if 'experiment' not in self.config:
            experiment_config_path = self.project_root / "problems" / self.problem / "settings.yaml"
            with open(experiment_config_path, 'r') as f:
                experiment_config = yaml.safe_load(f)
            self.config['experiment'] = experiment_config
        # Experiment config
        self.function_to_evolve = self.config['experiment']['function_to_evolve']  # the name of the function to be evolved
        self.obj_type = self.config['experiment']['obj_type'].lower().strip()
        assert self.obj_type in ['max', 'min'], f"Invalid objective type: {self.obj_type}"
        
        # =====SolutionDatabase settings=====
        self.reset_period_minutes = self.config["database"]["reset_period_minutes"]
        self.num_islands = self.config['database']['num_islands']
        self.num_parents = self.config['num_parents']
        
        # =====Vars updated during agent running=====
        # if no checkpoint specified, we need to create them
        if not checkpoint:
            # Initialize empty islands
            self._islands: list[Island] = []
            for i in range(self.num_islands):
                # Loop to initialize islands.
                self._islands.append(Island(self.config, island_id=i))
            # Best solution and its score per island.
            self._best_score_per_island: list[float] = [-float('inf')] * self.num_islands if self.obj_type == 'max' else [float('inf')] * self.num_islands
            # Best scores per test per island.
            self._best_solution_per_island = [None] * self.num_islands
            # Time of the last island reset.
            self._last_reset_time: float = time.time()
    
    def __len__(self):
        """The total number of solutions in the solution database.
        Note: repetitions may exist due to database initialization and island reset."""
        total = 0
        for island in self._islands:
            for cluster in island._clusters.values():
                total += len(cluster._solutions)
        return total
    
    
    def get_best(self):
        """Get the best solution of the database."""
        # find the best solution of all islands then return it; make use of self._best_score_per_island and self._best_solution_per_island
        if self.obj_type == 'max':
            best_island_idx = np.argmax(self._best_score_per_island)
        else:  # 'min'
            best_island_idx = np.argmin(self._best_score_per_island)

        return self._best_solution_per_island[best_island_idx]
    
    def sample(self, num_parents=None):
        """Draw samples from the database."""
        num_parents = num_parents or self.num_parents
        
        # Choose an island uniformly at random.
        island_id = np.random.randint(len(self._islands))
        
        # Sample from the island.
        samples = self._islands[island_id].sample(num_parents)
        
        return samples


    def _add_solution_to_island(self, solution: Solution) -> None:
        """Add a solution to a specified island."""
        island_id = solution.island_id
        
        self._islands[island_id].add(solution)
        
        if (self.obj_type == 'max' and solution.score > self._best_score_per_island[island_id]) \
            or (self.obj_type == 'min' and solution.score < self._best_score_per_island[island_id]):  # if program score is better than current best
            self._best_solution_per_island[island_id] = solution
            self._best_score_per_island[island_id] = solution.score
            print(f'\n>>>[Database] Best score of island {island_id} changed to {solution.score}')
            # log the best program found
            #timestamp = datetime.now().strftime("%Y-%m-%d_%H-%M-%S")
            #output_file = f"{self.project_root}/outputs/{self.algorithm}/{self.problem}/best_solution_{solution.id_str(self.algorithm)}.json"
            #with open(output_file, 'w') as f:
