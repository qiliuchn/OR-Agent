    def add_solution(self, solution: Solution) -> None:
        """Add a solution to the database."""        
        # Log newly obtained solution to the text file
        #timestamp = datetime.now().strftime("%Y-%m-%d_%H-%M-%S")
        #output_file = f"{self.project_root}/outputs/{self.algorithm}/{self.problem}/solution_{solution.id_str(self.algorithm)}.json"
        #with open(output_file, 'w') as f:
        #    json.dump(asdict(solution), f, indent=4, cls=NumpyEncoder)
        
        if solution.island_id is None:
            # If island_id is None, this is a program added at the beginning, so adding it to ALL islands.
            for island_id in range(len(self._islands)):
                # we will need to change the island_id of solution; make a deepcopy before changing
                sol_copy = deepcopy(solution)
                sol_copy.island_id = island_id
                self._add_solution_to_island(sol_copy)
        else:
            self._add_solution_to_island(solution)

        # Check whether it is time to reset an island.
        if time.time() - self._last_reset_time > self.reset_period_minutes * 60:
            self._last_reset_time = time.time()
            self.reset_islands()

    def add(self, solutions: Union[Solution, List[Solution]]) -> None:
        """Add a solution or a list of solutions to the database."""
        if not solutions:
            return
            
        if not isinstance(solutions, List):
            solutions = [solutions]
            
        for sol in solutions:
            self.add_solution(sol)
    
    
    def reset_islands(self) -> None:
        """
        Resets the weaker half of islands.
        
        Cf. Funsearch, paper, p9:
        Every 4h, we discard all the programs from the m/2 islands whose best instances have the lowest score. Each of these islands is
        then seeded with a single program, obtained by first choosing one of the surviving m/2 islands uniformly at random and then retrieving the
        highest-scoring program from that island (breaking ties in favour of older programs). The evolutionary process is then restarted from this
        state, in which the reset islands contain one high-performing program each (Extended Data Fig. 2).
        """
        # We sort best scores after adding minor noise to break ties.
        # np.argsort returns an array of integers representing the indices
        # np.argsort is ascending by default; smaller scores come first; small score islands are to be reset
        indices_sorted_by_score: np.ndarray = np.argsort(self._best_score_per_island + np.random.randn(len(self._best_score_per_island)) * 1e-6)
        if self.obj_type == 'min':
            indices_sorted_by_score = indices_sorted_by_score[::-1]  # reverse for 'min' objective
        num_islands_to_reset = self.num_islands // 2
        reset_islands_ids = indices_sorted_by_score[:num_islands_to_reset]  # the first half (with lowest scores) islands to reset
        keep_islands_ids = indices_sorted_by_score[num_islands_to_reset:]
        for island_id in reset_islands_ids:
            # Create a new island instance
            self._islands[island_id] = Island(self.config, island_id=island_id)
            self._best_score_per_island[island_id] = -float('inf') if self.obj_type == 'max' else float('inf')
            # Randomly choose a founder from the surviving islands to ignite the reset island
            # Note: for each island to reset, we randomly choose a founder independently
            founder_island_id = np.random.choice(keep_islands_ids)  # sample one island to keep
            # Make a deep copy of the founder solution to avoid interference; and remember to set the island_id
            founder_solution = deepcopy(self._best_solution_per_island[founder_island_id])
            founder_solution.island_id = island_id
            self._add_solution_to_island(founder_solution)


