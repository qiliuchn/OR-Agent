def parent_selection(population: list[Solution], 
                     obj_type: str, 
                     m=2, 
                     denominator_expansion=False
                     ) -> list[Solution]:
    """ 
    Select parents using rank-based probabilistic selection.
    Note: very similar to rank_select; return different number of parents
    
    Args:
        pop (list): Population of individuals; shape: (P, n_decap); already sorted according to the rewards in ascending order.
        obj_type (str): Objective type; either "min" or "max".
        m (int): Number of parents to select.
        denominator_expansion (bool): Whether to expand the denominator of the rank probability.
        
    Returns:
        parents (list): Parent individuals; shape: (m, n_decap).
    """
    # sort population based on obj
    # so we can use rank-based probabilistic selection
    if obj_type == "min":
        population.sort(key=lambda x: x.score)
    else:
        population.sort(key=lambda x: x.score, reverse=True)
    pop_size = len(population)
    
    # Compute rank probabilities
    if denominator_expansion:
        rank_probs = [1 / (i + 1 + pop_size) for i in range(pop_size)]
        # pop_size is added to the denominator;
        # This is in accordance with the EoH paper (page 5, right column, paragraph 4);
        # This practice is different with the rank_selection in ael.py.
    else:
        rank_probs = [1 / (i + 1) for i in range(pop_size)]

    rank_probs = np.array(rank_probs) / np.sum(rank_probs)
    #ranks = [i for i in range(len(pop))]
    #probs = [1 / (rank + 1 + len(pop)) for rank in ranks]
    #parents = random.choices(population, weights=rank_probs, k=m)
    parents = np.random.choice(population, size=m, replace=False, p=rank_probs)
    
    return parents   


