def random_select(population: list[Solution], 
                  pop_size
                  ) -> list[dict]:
    """
    Random selection, select individuals with equal probability.
    Sample from the population with uniform distribution.
    
    Args:
        population (list[dict]): Population
        pop_size (int): Population size
        
    Returns:
        list[dict]: Selected population; size: 2 * pop_size
    """
    selected_population = []
    # Eliminate invalid individuals
    population = [ind for ind in population if ind.score]
    if len(population) < 2:
        return None
    
    attempt = 0
    while len(selected_population) < 2 * pop_size:  
        attempt += 1
        # 2 * self.cfg.pop_size is the number of parents
        parents = np.random.choice(population, size=2, replace=False)  # select two parents at a time
        # If two parents have the same objective value, consider them as identical; otherwise, add them to the selected population
        if parents[0].score != parents[1].score:
            selected_population.extend(parents)
            
        if attempt > 1000:
            print(f"\n>>>[Utils] Random selection failed after 1000 attempts; len(population)={len(population)}; pop_size={pop_size}; selected_population size={len(selected_population)}")
            raise RuntimeError(">>>[Utils] Random selection failed after 1000 attempts")
    
    return selected_population


def response_to_individual(response: str, 
                           iteration: int, 
                           response_id: int, 
                           output_dir: str
                           ) -> dict:
    """
    Convert response to individual.

    Args:
        response (str): Response from LLM
        response_id (int): Response ID
        output_dir (str): Output directory

    Returns:
        dict: Individual
    """
    # Write response to file
    # Here the LLM response ```python...```code is written to the individual's file
    # Use f"{self.output_dir}/{solution.id_str(self.algorithm)}.txt" format
    code_filepath = f"{output_dir}/details/iter{iteration}_response{response_id}.txt"

    with open(code_filepath, 'w') as file:
        file.writelines(response + '\n')

    # Extract code from LLM response
    code = extract_python_code(response)

    # Create stdout file path
    output_filepath = f"{output_dir}/details/iter{iteration}_response{response_id}_stdout.txt"

    # Create individual
    individual = Solution(iteration=iteration,
                        response_id=response_id,
                        code=code,
                        code_filepath=code_filepath,
                        output_filepath=output_filepath,
                        )
    return individual


def responses_to_population(responses: list[str], 
                            iteration: int, 
                            output_dir: str
                            ) -> list[Solution]:
    """
    Convert responses to population.
    Invoke `response_to_individual()` for each response.
    
    Args:
        responses (list[str]): Responses from LLM
        iteration (int): Iteration number
        output_dir (str): Output directory
        
    Returns:
        list[dict]: Population; list of individuals
    """
    population = []
    for response_id, response in enumerate(responses):
        individual = response_to_individual(response=response, 
                                            iteration=iteration, 
                                            response_id=response_id, 
                                            output_dir=output_dir)
        population.append(individual)
    return population


def individual_to_str(individual: Solution) -> str:
    """
    Convert an individual to a string.
   
    Args:
        individual (dict): Individual
        
    Returns:
        str: Individual as a string
    """
    # if ind has obj
    if individual.score:
        score_str =  str(individual.score)
    else:
        score_str = "(not available)"

    ans = f"""
**Code**:
```python
{individual.code}
```

**Objective**: {score_str}
"""
    return ans.strip()







