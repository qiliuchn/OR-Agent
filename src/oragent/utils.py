def init_json_list(filepath: str):
    """If the file exists, clear the filepath to be a empty json list; if not, create a new empty json list file."""
    with open(filepath, "w") as fp:
        results = []
        json.dump(results, fp, indent=4, default=str)


def append_json_list(filepath: str, item: Any):
    """Update a JSON list file by appending a new item.

    Args:
        filepath: Path to the JSON file
        item: item to add to the JSON file
    """
    if os.path.exists(filepath):
        with open(filepath, "r") as fp:
            results = json.load(fp)
    else:
        results = []  # Note: if the file does not exist, we create a new one
    results.append(item)
    
    with open(filepath, "w") as fp:
        json.dump(results, fp, indent=4, default=str)
    

def file_to_string(filename) -> str:
    """Read a file as string.

    Args:
        filename: Path to the file to read

    Returns:
        String content of the file

    Raises:
        FileNotFoundError: If the file does not exist
        IsADirectoryError: If the path is a directory
    """
    if not os.path.exists(filename):
        raise FileNotFoundError(f"[Utils] File not found: {filename}")

    if os.path.isdir(filename):
        raise IsADirectoryError(f"[Utils] Path is a directory, not a file: {filename}")

    with open(filename, 'r') as file:
        return file.read()


def extract_thinking(text: str) -> Optional[str]:
    """
    Extract content from <thinking> tags in a string.
    
    Args:
        text: String that may contain <thinking>...</thinking> tags
        
    Returns:
        The content inside the thinking tags (stripped of leading/trailing whitespace),
        or None if no thinking tags are found
        
    Examples:
        >>> extract_thinking("<thinking>Analysis here</thinking>")
        'Analysis here'
        >>> extract_thinking("No tags here")
        None
        >>> extract_thinking("<thinking>\\nMulti-line\\nthinking\\n</thinking>")
        'Multi-line\\nthinking'
    """
    pattern = r'<thinking>(.*?)</thinking>'
    match = re.search(pattern, text, re.DOTALL)
    
    if match:
        return match.group(1).strip()
    return None


def extract_python_code(text: str) -> Optional[str]:
    """
    Extract Python code from markdown code blocks.
    
    Args:
        text: String containing markdown with ```python code blocks
        
    Returns:
        The extracted Python code, or None if no code block found
    """
    if not text:
        return None
    
    pattern = r'```python\s*(.*?)```'
    match = re.search(pattern, text, re.DOTALL)
    
    if match:
        code = match.group(1).strip()
        return code
    
    print("\n>>>[Utils] No python code block identified.")
    return None

def wrap_python_code(code: str) -> str:
    """
    Wrap Python code in ```python ... ``` fences.
    
    Args:
        code: Python code to wrap
        
    Returns:
        The wrapped code
    """
    return f"```python\n{code}\n```"


def extract_diff_block(text: str) -> Optional[str]:
    """
    Extract code diff ONLY from ```diff ... ``` fenced blocks.

    Rules:
    - Must be fenced with ```diff
    - Ignore other languages (python/json/etc.)
    - Ignore unfenced text
    - Return raw diff content without fences
    """
    if not text:
        return None

    match = re.search(
        r"```diff\s*\n(.*?)```",
        text,
        flags=re.DOTALL | re.IGNORECASE
    )

    if not match:
        print("\n>>>[Utils] No diff block identified.")
        return None

    return match.group(1).rstrip()


def extract_json(response: str) -> Union[List[Any], Dict[str, Any], None]:
    """
    Extract the first valid JSON object or array from a text response.
    The function may return either a JSON object or a JSON array

    This function is designed for LLM outputs, which often:
        - wrap JSON in ```json ... ``` fences
        - include explanatory text before / after the JSON
        - include invalid raw newlines inside JSON string values

    Strategy:
        1. Prefer extracting content inside a fenced code block.
        2. Otherwise, locate the first balanced {...} or [...] region.
        3. Parse with json.loads().
        4. If parsing fails, repair common LLM formatting errors and retry.

    Returns:
        Parsed JSON (dict or list) if successful, otherwise None.
    """

    if not response:
        return None

    # ------------------------------------------------------------
    # STEP 1: Strictly match ```json ... ``` fences only
    # ------------------------------------------------------------
    # handle default LLM output: JSON in ```json ... ``` fence
    match = re.search(
        r"```json\s*(.*?)\s*```",
        response,
        flags=re.DOTALL | re.IGNORECASE
    )

    # ------------------------------------------------------------
    # STEP 2: Try to decode directly
    # ------------------------------------------------------------    
    if not match:
        # for the case ```json ... ``` fence is not found
        # try to load directly
        try:
            return json.loads(response)
        except json.JSONDecodeError:
            print(f"\n>>>[Utils] JSON parsing failed: \n{response}")
        return None
    
    candidate = match.group(1).strip()
    # ------------------------------------------------------------
    # STEP 3: Attempt strict JSON parsing
    # ------------------------------------------------------------
    try:
        return json.loads(candidate)

    except json.JSONDecodeError:
        # ------------------------------------------------------------
        # STEP 4: Repair common LLM JSON errors and retry
        # ------------------------------------------------------------
        # Common issues:
        # - LLMs frequently emit raw newline characters inside JSON string values, which is illegal in JSON.
        # - Single quotes are NOT valid like {'hello': 'world'}
        # - trailing commas like {  "projects": ["A", "B",]}
        #
        # In this function, we only repair the first issue manually
        # TODO: there are other ways to handle those issues, like using LLM call for remedy
        # "remedy LLM response format error" - This requires further exploration, analysis, and validation, and is marked with a TODO flag
        # 
        # Examples:
        # s = '{"hello": "world"}'        # VALID
        # s = '{"hello": "world"\n}'      # VALID; \n is outside the string literal
        # s = '{"hello": "world\n"}'      # INVALID representation of \n; 
        #                                   The \n here is a literal newline character, not the two-character escape sequence \\n.
        #                                   JSON does not allow raw control characters (U+0000–U+001F) inside strings.
        #                                   json.loads('{"hello": "world\n"}') reports JSONDecodeError
        #                                   You need the backslash to be part of the JSON text itself.
        # s = "{'hello': 'world'}"        # INVALID using of single quotes; Single quotes are not permitted anywhere in JSON syntax
        #
        # This repair pass escapes:
        #   \n → \\n
        #   \r → \\r
        #   \t → \\t
        #
        # BUT ONLY when inside string literals.
        # ------------------------------------------------------------
        def escape_controls_in_strings(s: str) -> str:
            out = []
            in_string = False
            escape = False

            for c in s:  # Walks the JSON text one character at a time
                if in_string:
                    # Escapes illegal control characters only when they occur inside string literals.
                    if escape:
                        out.append(c)
                        escape = False
                    elif c == "\\":
                        out.append(c)
                        escape = True
                    elif c == '"':
                        out.append(c)
                        in_string = False
                    elif c == "\n":  # Invalid character inside string literal; replace with \\n
                        out.append("\\n")
                    elif c == "\r":
                        out.append("\\r")
                    elif c == "\t":
                        out.append("\\t")
                    else:
                        out.append(c)
                else:  # If outside of string literal, \n is valid character
                    out.append(c)
                    if c == '"':
                        in_string = True

            return "".join(out)

        # We deliberately do NOT auto-convert single quotes
        # The function is explicitly a JSON extractor, not a “parse whatever” extractor.
        # It is ambiguous and unsafe
        
        # Apply repair and retry parsing
        fixed = escape_controls_in_strings(candidate)

        try:
            return json.loads(fixed)
        except Exception:
            # Still invalid — give up
            print(f"\n>>>[Utils] No JSON block identified: {fixed}")
            return None


def add_imports_to_code(code: str) -> str:
    """ 
    Add imports to the code at the beginning of the code.
    This simple trick can settle a common issue of LLM generated code - forgetting to import relevant libs.
    TODO: you may want to customize this according to your problems
    """
    additional_imports = [
        "import os",
        "import sys",
        "import time",
        "import random",
        "import math",
        "import json",
        "import numpy as np",
        "import pandas as pd",
        "import scipy",
        "import traci",
        "import torch",
    ]
    return "\n".join(additional_imports) + "\n\n" + code


def is_valid(solution: Solution)-> bool:
    """
    Check if the solution is valid.
    Here we check three important fields: idea, code, and score.
    """
    return (solution.idea is not None) and (solution.code is not None) and (solution.score is not None)


def parents_to_str(parent_solutions: Union['Solution']=None) -> str:
    """Convert a list of solutions to a string.

    Example:
----------------------------------------
Parent #1:
----------------------------------------
**Idea**: 
Parent idea 1

**Code**:
```python
def parent1(): pass
```

**Metrics**:
{}

**Feature**
None

**Score**:
0.7

**Summary**:
None

----------------------------------------
Parent #2:
----------------------------------------
...
    """
    # Error handling
    if not parent_solutions:
        print("\n>>>[Utils] Warning: no parent solutions provided!")
        return None
    
    if parent_solutions and not isinstance(parent_solutions, list):
        parent_solutions = [parent_solutions]
    
    parent_solutions_str = ""
    if parent_solutions:
        for i, parent in enumerate(parent_solutions):
            parent_solutions_str = parent_solutions_str + f"\n{'-'*40}\nParent #{i + 1}:\n{'-'*40}\n" + str(parent) + '\n'
    return parent_solutions_str.strip()


def truncate(raw_output: str, max_lines=100) -> str:
    """
    Truncate experiment output if it's too verbose.
    
    Args:
        raw_output (str): experiment output
        max_lines (int): max number of lines to keep; default: 100
        
    Returns:
        truncated (str): truncated output
    """
    raw_output = raw_output.strip()
    lines = raw_output.splitlines()
    total_lines = len(lines)

    if total_lines <= max_lines:
        return raw_output

    # Keep only the first max_lines lines
    truncated = "\n".join(lines[:max_lines])
    # Add annotation so that LLM will know the result is too verbose; this is important!
    truncated += f"\n...\n[Output truncated: {total_lines} total lines, showing first {max_lines} lines]"
    
    # TODO: this represents a simple logic to shorten verbose environment output
    # there are alternatives; like you can extract important info, invoke LLM to compress to provide a summary, etc.
    # "how to manage and compress context?" - This requires further exploration, analysis, and validation, and is marked with a TODO flag
    return truncated


def update_parameter(curr_code: str, parameter_definitions: str):
    """
    Update parameter values in the current solution code.
    Parses parameter definitions and updates their values in the solution's code.
    If a parameter is not found in the current code, the definition is silently
    ignored to ensure robustness.
    
    Args:
        curr_code (str): The current code string of a solution.
        parameter_definitions (str): Parameter definitions to update, with each
            definition on a separate line (e.g., "a = 1.2\nb = 0.5").
    
    Returns:
        str: The updated code with modified parameter values.
    
    Example:
        If curr_code contains "a = 1.0" and parameter_definitions is "a = 1.2",
        the result will have "a = 1.2" in place of "a = 1.0".
    """
    # Split parameter definitions into individual lines
    definitions = parameter_definitions.strip().split('\n')
    
    for definition in definitions:
        definition = definition.strip()
        if not definition or '=' not in definition:
            continue
        
        # Parse parameter name and new value
        try:
            param_name, new_value = definition.split('=', 1)
            param_name = param_name.strip()
            new_value = new_value.strip()
        except ValueError:
            continue
        
        # Pattern to match parameter assignment
        # Matches: param_name = <any_value> (with optional whitespace)
        pattern = rf'^(\s*){re.escape(param_name)}\s*=\s*(.+?)(\s*#.*)?$'
        
        # Replace parameter value line by line
        lines = curr_code.split('\n')
        updated = False
        for i, line in enumerate(lines):
            match = re.match(pattern, line)
            if match:
                indent = match.group(1)
                comment = match.group(3) if match.group(3) else ''
                lines[i] = f'{indent}{param_name} = {new_value}{comment}'
                updated = True
                break  # Only replace first occurrence
        
        if updated:
            curr_code = '\n'.join(lines)
    
    return curr_code


def update_code(curr_code: str, code_diff: str):
    """
    Update code blocks in the current solution code.

    Args:
        curr_code (str): The current code string of a solution.
        code_diff (str): code modifications in conflict markers style, example:
<<<<<<< SEARCH
...
=======
...
>>>>>>> REPLACE
<<<<<<< SEARCH
...
=======
...
>>>>>>> REPLACE

    Returns:
        str: The updated code.
    """
    # Split the code_diff into individual conflict blocks
    lines = code_diff.split('\n')
    result = curr_code
    i = 0

    while i < len(lines):
        line = lines[i]
        # Look for conflict marker start
        if line.strip() == '<<<<<<< SEARCH':
            search_start = i
            # Find the ======= marker
            while i < len(lines) and lines[i].strip() != '=======':
                i += 1
            if i >= len(lines):
                break  # Malformed diff
            search_end = i
            i += 1  # Skip =======

            # Find the >>>>>>> REPLACE marker
            replace_start = i
            while i < len(lines) and lines[i].strip() != '>>>>>>> REPLACE':
                i += 1
            if i >= len(lines):
                break  # Malformed diff
            replace_end = i
            i += 1  # Skip >>>>>>> REPLACE

            # Extract search and replace blocks
            search_block = '\n'.join(lines[search_start + 1:search_end])
            replace_block = '\n'.join(lines[replace_start:replace_end])

            # Apply the replacement - replace only the first occurrence
            if search_block in result:
                # Find the position of the first occurrence
                pos = result.find(search_block)
                if pos != -1:
                    # Replace only at this position
                    result = result[:pos] + replace_block + result[pos + len(search_block):]
            else:
                # If exact match not found, try to find a similar block
                # by removing trailing whitespace from each line
                search_lines = [l.rstrip() for l in search_block.split('\n')]
                result_lines = result.split('\n')

                # Try to find the block in the result (preserving original indentation)
                for j in range(len(result_lines) - len(search_lines) + 1):
                    # Compare with trailing whitespace removed
                    if [l.rstrip() for l in result_lines[j:j + len(search_lines)]] == search_lines:
                        # Found a match, replace it
                        before = '\n'.join(result_lines[:j])
                        after = '\n'.join(result_lines[j + len(search_lines):])
                        result = before + '\n' + replace_block + '\n' + after
                        break
        else:
            i += 1

    return result





