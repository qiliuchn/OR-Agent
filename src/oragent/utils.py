class LLMClient:
    def __init__(self, config=None, llm_provider=None, model_name=None, **kwargs):
        """
        Initialize the LLM client.
        If `llm_provider` is not in ['openai', 'qwen', 'deepseek'], you should set `llm_provider` to be None and 
        provide the following parameters in `kwargs`: 
        - `api_key`
        - `base_url`
        
        Args:
            llm_provider (str): The LLM provider name
            model_name (str): The model name to use
            **kwargs: Additional arguments passed to the OpenAI client
        """
        self.package_dir = Path(__file__).parent
        self.project_root = Path.cwd()
        if config:
            self.config = config
        else:
            # Load built-in config if config is not provided
            with open(f'{self.package_dir}/config.yaml', 'r') as f:
                self.config = yaml.safe_load(f)
        
        # -----LLM client settings-----
        self.max_tries = self.config["model"]["max_retries"]
        # If LLM is not specified, use default LLM settings from config file
        self.llm_provider = llm_provider or self.config["model"]["llm_provider"]
        self.model_name = model_name or self.config["model"]["model_name"]
        
        # Create client
        if "openai" in self.llm_provider.lower():
            self.client = OpenAI(
                api_key=os.getenv("OPENAI_API_KEY"),
                base_url="https://api.openai.com/v1",
                **kwargs
            )
        elif "qwen" in self.llm_provider.lower():
            self.client = OpenAI(
                api_key=os.getenv("DASHSCOPE_API_KEY"),
                base_url="https://dashscope.aliyuncs.com/compatible-mode/v1",
                **kwargs
            )
        elif "deepseek" in self.llm_provider.lower():
            self.client = OpenAI(
                api_key=os.getenv("DEEPSEEK_API_KEY"),
                base_url="https://api.deepseek.com",
                **kwargs
            )
        else:
            try:
                self.client = OpenAI(
                    **kwargs  # include `api_key` and `base_url` in `kwargs` in this case
                )
            except:
                raise ValueError(f"Invalid model config: {kwargs}")


    def chat(self, messages: list[dict], **kwargs) -> str:
        """
        Generate one response using OpenAI Chat Completions API.
        
        Args:
            messages (list[dict]): One round of messages
            **kwargs: Additional arguments passed to the chat completions API
            
        Returns:
            str: LLM response string
        """
        choices = None
        for attempt in range(self.max_tries):
            try:
                response = self.client.chat.completions.create(
                    model=self.model_name,
                    messages=messages,
                    **kwargs
                )
                choices = response.choices
                if not choices:
                    print("\n>>>[LLMClient] None response generated")
                else:
                    # check to make sure that choices is not none, then you can break! 
                    # otherwise, sometimes it returns None, and you will regard this as a successful generation
                    break
            except Exception as e:
                sleep_time = random.randint(3, 60)
                print(f"\n>>>[LLMClient] Attempt {attempt + 1} failed with error: {e}; sleep for {sleep_time} seconds")
                time.sleep(sleep_time)
                # Note: add random sleep time to avoid too frequent LLM call
                # TODO: this is a simple trick; could be made better
                # "devise technique to avoid LLM calls flooding" - This requires further exploration, analysis, and validation, and is marked with a TODO flag
        
        if choices is None:
            print("\n>>>[LLMClient] All retry attempts failed!")
            raise RuntimeError("\n>>>[LLMClient] All retry attempts failed")
        
        return choices[0].message.content

    def multi_chat(self, messages_list: list[list[dict]], n: int = 1, **kwargs) -> list[str]:
        """
        This function serves two goals:
        1) Process multiple conversations concurrently - Takes a list of message rounds 
           and generates one response for each message round in parallel using ThreadPoolExecutor.
           In this case, `n` must be one;
        2) Take single message round, then generate multiple responses for this conversation - 
           The `n` parameter controls how many responses to generate.

        Args:
            messages_list (list[list[dict]]): List of message rounds;
                An example of messages_list:
                messages_list = [
                    [
                        {"role": "system", "content": "You are a helpful assistant."},
                        {"role": "user", "content": "Hello!"},
                    ],
                    [
                        {"role": "system", "content": "You are a knowledgeable guide."},
                        {"role": "user", "content": "How are you?"},
                    ],
                    [
                        {"role": "system", "content": "You are a witty comedian."},
                        {"role": "user", "content": "Tell me a joke."},
                    ]
                ]
                messages_list[i] is a list of messages (a multi-round chat)
            n (int): Number of responses to generate
            **kwargs: Additional arguments passed to the chat completions API
        
        Returns:
            list[str]: A list of response strings
        """
        assert isinstance(messages_list, list), "messages_list should be a list."
        if not isinstance(messages_list[0], list):
            messages_list = [messages_list]

        if len(messages_list) > 1:
            assert n == 1, "When processing multiple conversations, n must be 1"
        elif n > 1:
            # Note messages_list has to has length == 1 before this step; 
            # and we need to generate n completions for this message; 
            # so we expand the messages_list to n copies; and later we will use `concurrent` to process them in parallel
            messages_list = messages_list * n

        # Async LLM call
        with concurrent.futures.ThreadPoolExecutor() as executor:
            args = [dict(messages=messages, **kwargs) for messages in messages_list]
            contents = list(executor.map(lambda p: self.chat(**p), args))
        
        return contents





