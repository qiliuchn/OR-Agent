@dataclass
class Solution:
    _next_id = 0  # Class-level counter
    """
    `Solution` dataclass fields:
    (IDs)
    - `id` (int): Auto-incremented unique ID for each solution.
    - `lead_agent_id` (int): The ID of the lead agent who generated this solution. Default: `None`.
    - `research_round`(int): The research round number when this solution is generated by the LeadAgent. Default: `None`.
    - `solution_count` (int): The count of the solution in the current research round.  Default: `None`.
    (Body)
    - `idea` (str): The conceptual approach of the solution. Generated by the IdeaAgent. Default: `None`.
    - `code` (str): The code implementation of the idea. Generated by the CodeAgent. Default: `None`.
    - `code_filepath` (str): The path to the code file: f"{output_dir}/{id_str}_solution.py". Generated by the Evaluator. Default: `None`. 
    - `output` (str): The stdout of solution execution. Generated by the Evaluator. Default: `None`.
    - `output_filepath` (str): The path to the stdout file: f"{output_dir}/{id_str}_stdout.txt". Generated by the Evaluator. Default: `None`.
    - `metrics` (Dict): Performance metrics of the solution. Generated by the Evaluator. Default: `{}`.
    - `features` (Tuple[int, ...]): Feature vector of the solution, used by the MAP-Elites-based solution database for indexing. Generated by the Evaluator. Default: `None`.
    - `score` (float): Overall score of the solution. Generated by the Evaluator. Default: `None`.
    - `summary` (str): Final verdict on the solution's quality along with insights for future iterations. Generated by the ExperimentAgent. Default: `None`.
    - `island_id` (int): The ID of the island where the solution was found in solution database. Used by OR-Agent and FunSearch. Default: `None`.
    (The following fields are used to store temporary data generated during experiments)
    - `intermediate_codes` (List[str]): Code generated during iterative experiments. Generated by ExperimentAgent. Default: `[]`.
    - `intermediate_outputs` (List[str]): Results collected during iterative experiments. Generated by the Evaluator. Default: `[]`.
    - `intermediate_metrics` (List[Dict]): Performance metrics collected during iterative experiments. Generated by the Evaluator. Default: `[]`.
    - `intermediate_features` (List[Tuple[int, ...]]): Feature vectors collected during iterative experiments. Generated by the Evaluator. Default: `[]`.
    - `intermediate_scores` (List[float]): Scores collected during iterative experiments. Generated by the Evaluator. Default: `[]`.
    - `intermediate_actions` (List[str]): Actions during experiments. Generated by the ExperimentAgent. Default: `[]`.
    (The following ID fields are used by ReEvo, EoH, AEL, and FunSearch; kept for compatibility)
    - `iteration` (int): The iteration number when this solution was found. Default: `None`.
    - `response_id` (int): The index of the response from the LLM. Default: `None`.
    
    Usage:
    Convert Solution instance to Dict: `sol_dict = dataclasses.asdict(sol)`
    Convert Dict to Solution instance: `sol = Solution(**sol_dict)`
    """
    # PS: variables defined inside the @dataclass field list (i.e., annotated with a type) become instance attributes.
    # Note: don NOT use [], {} for list or dict initialization; dangerous - objects will share the same instance! Use factory method
    id: int = None  # Auto-incrementing unique ID
    lead_agent_id: int = None  # ID of lead agent who generated the solution
    research_round: int = None  # research round when the solution is generated
    solution_count: int = None  # solution count when the solution is generated
    idea: Optional[str] = None
    code: Optional[str] = None
    code_filepath: Optional[str] = None
    output: Optional[str] = None
    output_filepath: Optional[str] = None
    metrics: Dict = field(default_factory=dict)  # Don't use {}
    features: Optional[Tuple[int, ...]] = None
    score: Optional[float] = None
    summary: Optional[str] = None
    island_id: Optional[int] = None
    intermediate_codes: List[str] = field(default_factory=list)
    intermediate_outputs: List[str] = field(default_factory=list)
    intermediate_metrics: List[Dict] = field(default_factory=list)
    intermediate_features: List[Tuple[int, ...]] = field(default_factory=list)
    intermediate_scores: List[float] = field(default_factory=list)
    intermediate_actions: List[str] = field(default_factory=list)
    # (The following fields are used by ReEvo, EoH, AEL, and FunSearch; kept for compatibility)
    iteration: Optional[int] = None
    response_id: Optional[int] = None
    
    def __post_init__(self):
        """Assign auto-incrementing ID if not provided."""
        if self.id is None:
            self.id = Solution._next_id
            Solution._next_id += 1

    def __str__(self) -> str:
        """Return a human-readable string representation of the Solution.
        PS: Intermediate experiment results are NOT included. Only include the body.
        
        **Example output:**
Idea: Use dynamic programming...
Code: def solve(n):...
Features: (10, 20, 5)
Metrics: {'accuracy': 0.92, 'speed': 1.23}
Score: 0.85
Summary: Good solution with high accuracy...
"""
        solution_str = f"""
**ID**
{self.id}

**Idea**: 
{self.idea}

**Code**:
```python
{self.code}
```

**Metrics**:
{self.metrics}

**Feature**
{self.features}

**Score**:
{self.score}

**Summary**:
{self.summary}
"""
        return solution_str.strip()


    def id_str(self, algorithm='oragent') -> str:
        """Get a string for the solution identity.
        PS: fields like iteration, response_id are added for better inspection.
        TODO: Revise it to display only `id` if you prefer more concise naming.
        # "customize visualization techniques" - This requires further exploration, analysis, and validation, and is marked with a TODO flag
        """
        if algorithm == "oragent":
            return f"lead{self.lead_agent_id}_round{self.research_round}_count{self.solution_count}_id{self.id}"
        else:
            return f"iter{self.iteration}_response{self.response_id}"
        
    def performance_str(self) -> str:
        """Return a string summarizing the solution's performance."""
        performance_str = f"""
**Metrics**:
{self.metrics}

**Score**:
{self.score}
"""
        return performance_str.strip()
    
    def performance_summary_str(self) -> str:
        """Return a string summarizing the solution's performance and summary."""
        performance_summary_str = f"""
**Metrics**:
{self.metrics}

**Score**:
{self.score}

**Summary**:
{self.summary}
"""
        return performance_summary_str.strip()
    
    def idea_performance_summary_str(self) -> str:
        """Return a string summarizing the solution's idea, performance, and summary."""
        idea_performance_summary_str = f"""
**Idea**:
{self.idea}

**Metrics**:
{self.metrics}

**Score**:
{self.score}

**Summary**:
{self.summary}
"""
        return idea_performance_summary_str.strip()
    
    def experiment_history(self, num_experiments=None) -> str:
        """
        Generate experiment history string by concatenating intermediate experiment results and reflections.
        
        Args:
            num_experiments (int): Number of experiments to include; default: None (includes all).
                If the allowed number of experiments is large, we recommend set `num_experiments` to avoid context growing too large for experiment agent.
        
        Returns:
            experiment_history_str (str): Formatted experiment history string.
            
        Example:
----------------------------------------
Experiment #1:
----------------------------------------
**Stdout**:
Test case 1 passed with score 0.8

**Metrics**:
{'accuracy': 0.8, 'speed': 2.0}

**Features**:
(8, 15, 3)

**Score**: 0.8

**Reflections and actions**:
Increased timeout limit

----------------------------------------
Experiment #2:
----------------------------------------
...
        """
        # Limit to num_experiments if specified
        # solution intermediate outputs and metrics length = actions length + 1
        # since the last evaluation remains to be reflected
        # we use len(self.intermediate_actions) to generate experiment history
        num_experiments = num_experiments or len(self.intermediate_actions)
            
        # Experiment tracking - print alternately
        # concat results of last `num_experiments` experiment results.
        experiment_history_str = ''
        start_index = max(0, len(self.intermediate_actions) - num_experiments)
        for i in range(start_index, len(self.intermediate_actions)):
            tmp_str = f"\n{'-'*40}\nExperiment #{i + 1}:\n{'-'*40}\n"
            tmp_str += f"**Stdout**:\n{self.intermediate_outputs[i]}\n\n"
            tmp_str += f"**Metrics**:\n{self.intermediate_metrics[i]}\n\n"
            tmp_str += f"**Features**:\n{self.intermediate_features[i]}\n\n"
            tmp_str += f"**Score**: {self.intermediate_scores[i]}\n\n"
            tmp_str += f"**Reflections and actions**:\n{self.intermediate_actions[i]}\n"
            experiment_history_str += tmp_str
        return experiment_history_str.strip()





