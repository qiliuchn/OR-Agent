# Evaluate TSP-GLS
""" 
GLS is a metaheuristic that enhances local search by dynamically penalizing features of poor-quality solutions. For TSP:
Local Search: Uses standard operators (2-opt, relocate) to improve tours
- Penalty Mechanism: When stuck in local optima, identifies "bad" edges (high utility) and penalizes them
- Utility Function: util = guide[u,v] / (1 + penalty[u,v]) - guides which edges to penalize
- Perturbation: Temporarily modifies objective function by adding penalties, forcing search to explore different regions
- Iterative Process: Alternates between local search and perturbation until convergence
- The guide matrix (generated by `heuristics` function) typically contains edge desirability scores (e.g., edge lengths or other heuristics)
"""
